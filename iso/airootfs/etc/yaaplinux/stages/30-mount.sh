#!/usr/bin/env bash
# stages/30-mount.sh — mount the btrfs subvolumes and ESP at their final
# locations so pacstrap and chroot operate on the target tree (spec §6.2).

STAGE_ID="30-mount"

_mount_opts() { echo "noatime,compress=zstd:3,space_cache=v2"; }

run_stage() {
    local dev esp root_part
    dev="$(cfg_get storage.device)"
    root_part="$(cfg_get storage.root_partition)"
    local luks; luks="$(cfg_get disk.luks.enabled)"
    local btrfs_dev="$root_part"
    [ "$luks" = true ] && btrfs_dev="/dev/mapper/$(cfg_get disk.luks.open_mapper)"

    local esp_dev; esp_dev="$( { case "$(basename "$dev")" in nvme*|mmcblk*) echo "${dev}p1";; *) echo "${dev}1";; esac; } )"

    mkdir -p "$TARGET_ROOT"
    log_info "mounting btrfs root subvolume @ -> /"
    mount -o "$(_mount_opts)" "$btrfs_dev" "$TARGET_ROOT" >>"$YAAP_LOG" 2>&1 \
        || die "root mount failed"

    # Bind subvolumes into place.
    mount_sub "@home"   "$TARGET_ROOT/home"
    mount_sub "@swap"   "$TARGET_ROOT/swap"
    mount_sub "@snapshots" "$TARGET_ROOT/.snapshots"

    # ESP.
    mkdir -p "$TARGET_ROOT/boot" "$TARGET_ROOT/boot/efi"
    log_info "mounting ESP -> /boot/efi"
    mount "$esp_dev" "$TARGET_ROOT/boot/efi" >>"$YAAP_LOG" 2>&1 || die "ESP mount failed"

    # Unattended LUKS: publish the staged passphrase as an ESP keyfile so the
    # system is unlockable after reboot. (Security note: a keyfile on the
    # unencrypted ESP weakens physical-attack protection; this is the trade-off
    # of unattended LUKS. Documented in the post-install report.)
    if [ "$(cfg_get disk.luks.unattended)" = true ] && [ -f "$YAAP_LUKS_PASSPHRASE_FILE" ]; then
        local mapper; mapper="$(cfg_get disk.luks.open_mapper)"
        mkdir -p "$TARGET_ROOT/boot/efi/keys"
        cp "$YAAP_LUKS_PASSPHRASE_FILE" "$TARGET_ROOT/boot/efi/keys/$mapper.key"
        chmod 600 "$TARGET_ROOT/boot/efi/keys/$mapper.key" 2>/dev/null || true
        log_info "unattended LUKS keyfile written to /boot/efi/keys/$mapper.key"
    fi

    store_uuids "$btrfs_dev"
    cfg_set meta.stage "pacstrap"
    log_info "mount tree ready under $TARGET_ROOT"
}

mount_sub() {
    local sub="$1" dest="$2"
    [ -d "$dest" ] || mkdir -p "$dest"
    mount -o "$(_mount_opts)" "$TARGET_ROOT/$sub" "$dest" >>"$YAAP_LOG" 2>&1 \
        || log_warn "could not mount subvolume /$sub -> $dest (dir left in place)"
}

store_uuids() {
    local dev="$1"
    local root_uuid esp_uuid
    root_uuid="$(blkid -s UUID -o value "$dev" 2>/dev/null)"
    esp_uuid="$(blkid -s UUID -o value "$( { case "$(basename "$(cfg_get storage.device)")" in nvme*|mmcblk*) echo "$(cfg_get storage.device)p1";; *) echo "$(cfg_get storage.device)1";; esac; } )" 2>/dev/null)"
    cfg_set storage.root_uuid "$root_uuid"
    cfg_set storage.esp_uuid "$esp_uuid"
    log_info "root UUID=$root_uuid esp UUID=$esp_uuid"

    # Persist fstab-ish mount options for the target's /etc/fstab generation.
    write_fstab "$root_uuid" "$esp_uuid"
}

write_fstab() {
    local root_uuid="$1" esp_uuid="$2"
    local opts; opts="$(_mount_opts)"
    local swap_style; swap_style="$(cfg_get disk.swap.style)"
    local hibernation; hibernation="$(cfg_get disk.swap.hibernation)"
    {
        echo "# /etc/fstab — generated by YaapLinux installer"
        echo "UUID=$root_uuid / btrfs $opts 0 1"
        echo "UUID=$root_uuid /home btrfs $opts,subvol=@home 0 1"
        echo "UUID=$root_uuid /swap btrfs $opts,subvol=@swap 0 1"
        echo "UUID=$root_uuid /.snapshots btrfs $opts,subvol=@snapshots 0 1"
        echo "UUID=$esp_uuid /boot/efi vfat umask=0077 0 1"
        # The btrfs swapfile only exists when hibernation is enabled (stage 20
        # creates it then). zram handles runtime swap otherwise.
        if [ "$hibernation" = true ] && [ "$swap_style" = zram_plus_file ]; then
            echo "/swap/swap none swap defaults 0 0"
        fi
    } > "$TARGET_ROOT/etc/fstab"
    log_info "wrote $TARGET_ROOT/etc/fstab"
}
