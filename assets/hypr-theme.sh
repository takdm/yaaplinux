#!/usr/bin/env bash
# hypr-theme.sh — generate a coherent palette across all layers from a single
# Base16 scheme (spec §9.4).
#
# Usage:
#   hypr-theme apply <scheme> [--light] [--accent <hex>]
#   hypr-theme list
#
# Reads assets/base16/<scheme>.yaml (keys base00..base0F), writes per-tool
# configs under the target user's ~/.config. Reload is live where supported;
# apps needing a restart are reported.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE16_DIR="$SCRIPT_DIR/base16"
TARGET_USER="${YAAP_THEME_USER:-${1:-$USER}}"
SCHEME=""
LIGHT=0
ACCENT=""
ACTION="apply"

# Parse: first positional is the action/scheme.
if [ "${1:-}" = "list" ]; then
    ACTION="list"
    shift
fi
SCHEME="${1:-}"
shift || true
while [ $# -gt 0 ]; do
    case "$1" in
        --light) LIGHT=1 ;;
        --accent) ACCENT="$2"; shift ;;
    esac
    shift
done

list_schemes() {
    echo "Available Base16 schemes:"
    for f in "$BASE16_DIR"/*.yaml; do
        [ -f "$f" ] || { echo "  (none found in $BASE16_DIR)"; exit 0; }
        echo "  $(basename "$f" .yaml)"
    done
}

if [ "$ACTION" = list ]; then list_schemes; exit 0; fi

[ -n "$SCHEME" ] || { echo "usage: hypr-theme apply <scheme> [--light] [--accent <hex>]" >&2; exit 1; }
SCHEME_FILE="$BASE16_DIR/$SCHEME.yaml"
[ -f "$SCHEME_FILE" ] || { echo "scheme not found: $SCHEME ($SCHEME_FILE)" >&2; exit 1; }

# Load base00..base0F from the scheme YAML.
declare -A C
while IFS= read -r line; do
    case "$line" in
        base0[0-9A-F]:*)
            k="${line%%:*}"; v="${line#*: }"
            C[$k]="$v" ;;
    esac
done < "$SCHEME_FILE"

[ -n "${C[base00]:-}" ] || { echo "scheme missing base00" >&2; exit 1; }
[ -n "$ACCENT" ] && C[base0A]="$ACCENT"

BASE="${C[base00]}" FG="${C[base05]}" ACC="${C[base0A]}"
BASE1="${C[base01]}" BASE2="${C[base02]}" BASE3="${C[base03]}"
BASE4="${C[base04]}" BASE6="${C[base06]}" BASE7="${C[base07]}"

RESTART_NEEDED=""

write_file() {  # write_file <path> <<content
    local path="$1"; mkdir -p "$(dirname "$path")"
    cat > "$path"
}

# --- Hyprland theme.lua ----------------------------------------------------
write_file "$HOME/.config/hypr/theme.lua" <<EOF
-- Generated by hypr-theme.sh from Base16 scheme '$SCHEME' ($([ "$LIGHT" = 1 ] && echo light || echo dark))
THEME = {
    base   = "$BASE",
    base1  = "$BASE1",
    base2  = "$BASE2",
    base3  = "$BASE3",
    fg     = "$FG",
    accent = "$ACC",
}
EOF

# --- Kitty -----------------------------------------------------------------
write_file "$HOME/.config/kitty/theme.conf" <<EOF
foreground $FG
background $BASE
color0 $BASE3
color1 ${C[base08]}
color2 ${C[base0B]}
color3 ${C[base0A]}
color4 ${C[base0D]}
color5 ${C[base0E]}
color6 ${C[base0C]}
color7 $BASE7
color8 ${C[base03]}
color9 ${C[base08]}
color10 ${C[base0B]}
color11 ${C[base0A]}
color12 ${C[base0D]}
color13 ${C[base0E]}
color14 ${C[base0C]}
color15 $BASE4
EOF

# --- Fuzzel ----------------------------------------------------------------
write_file "$HOME/.config/fuzzel/fuzzel.ini" <<EOF
[main]
font=Sans:pixelsize=14
background=${BASE}ee
layer=overlay
dmenu-mode=s
[border]
radius=8
width=2
color=${ACC}aa
[text]
foreground=$FG
[match]
foreground=$FG
[selection]
background=${ACC}cc
EOF

# --- Mako ------------------------------------------------------------------
write_file "$HOME/.config/mako/config" <<EOF
background-color=${BASE}f2
text-color=$FG
border-color=${ACC}
border-size=2
padding=10
margin=10
EOF

# --- Waybar ----------------------------------------------------------------
write_file "$HOME/.config/waybar/style.css" <<EOF
* { font-family: "Sans"; font-size: 13px; }
window { background: ${BASE}ee; }
#window-controller, #custom-launcher { color: $FG; }
#tray menu { background: $BASE; color: $FG; }
#mode, #custom-accent { background: $ACC; color: $BASE; }
EOF

# --- GTK 3 -----------------------------------------------------------------
write_file "$HOME/.config/gtk-3.0/gtk.css" <<EOF
@define-color bg_color $BASE;
@define-color fg_color $FG;
@define-color selected_bg_color $ACC;
@define-color selected_fg_color $BASE;
@define-color border_color $BASE4;
EOF

# --- GTK 4 (nwg-look does NOT cover GTK4; set via gsettings per spec §9.3) --
write_file "$HOME/.config/gtk-4.0/gtk.css" <<EOF
@define-color theme_bg_color $BASE;
@define-color theme_fg_color $FG;
@define-color theme_selected_bg_color $ACC;
@define-color theme_selected_fg_color $BASE;
EOF
gsettings set org.gnome.desktop.interface color-scheme "$([ "$LIGHT" = 1 ] && echo prefer-light || echo prefer-dark)" 2>/dev/null \
    && RESTART_NEEDED="$RESTART_NEEDED gtk4"

# --- Qt6 (qt6ct) -----------------------------------------------------------
write_file "$HOME/.config/qt6ct/qt6ct.conf" <<EOF
[Appearance]
color_scheme_path=$HOME/.config/qt6ct/colors/$SCHEME.conf
cursor_theme=bibata
EOF
mkdir -p "$HOME/.config/qt6ct/colors"
write_file "$HOME/.config/qt6ct/colors/$SCHEME.conf" <<EOF
[ColorScheme]
foreground=$FG
background=$BASE
selection=$ACC
EOF

# --- Cursors ---------------------------------------------------------------
if [ -d /usr/share/icons/Bibata-Modern-Classic ] || [ -d /usr/share/icons/bibata-cursor-theme ]; then
    gsettings set org.gnome.desktop.interface cursor-theme Bibata-Modern-Classic 2>/dev/null || true
fi

echo "Applied Base16 scheme '$SCHEME' ($([ "$LIGHT" = 1 ] && echo light || echo dark)) to:"
echo "  ~/.config/hypr/theme.lua"
echo "  ~/.config/kitty/theme.conf"
echo "  ~/.config/fuzzel/fuzzel.ini"
echo "  ~/.config/mako/config"
echo "  ~/.config/waybar/style.css"
echo "  ~/.config/gtk-3.0/gtk.css, gtk-4.0/gtk.css"
echo "  ~/.config/qt6ct/qt6ct.conf"
[ -n "$RESTART_NEEDED" ] && echo "Restart needed:${RESTART_NEEDED}"
echo "Live reload: hyprctl reload ; makoctl reload"
