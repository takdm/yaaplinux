#!/usr/bin/env bash
# stages/50-base-config.sh — chroot configuration (spec §7.2). Locale, clock,
# hostname, initramfs, user, sudo, network, microcode. Also persists the
# installer config into the target and copies pacman hooks.

STAGE_ID="50-base-config"

run_stage() {
    ensure_chroot
    configure_locale
    configure_clock
    configure_hostname
    install_microcode
    configure_initramfs
    create_user
    configure_sudo
    configure_network
    copy_installer_artifacts
    cfg_set meta.stage "drivers-media"
    log_info "base config complete"
}

ensure_chroot() {
    [ -x "$TARGET_ROOT/usr/bin/pacman" ] || die "target is not a bootable system (run pacstrap)"
}

configure_locale() {
    local lang; lang="$(cfg_get locale.lang)"; lang="${lang:-en_US.UTF-8}"
    log_info "locale: $lang"
    echo "${lang%.UTF-8}.UTF-8" > "$TARGET_ROOT/etc/locale.gen"
    arch-chroot "$TARGET_ROOT" locale-gen >>"$YAAP_LOG" 2>&1 || die "locale-gen failed"
    printf 'LANG=%s\n' "${lang%.UTF-8}.UTF-8" > "$TARGET_ROOT/etc/locale.conf"
    # Keyboard (optional override).
    local keymap; keymap="$(cfg_get locale.keymap)"; keymap="${keymap:-us}"
    echo "KEYMAP=$keymap" > "$TARGET_ROOT/etc/vconsole.conf"
    arch-chroot "$TARGET_ROOT" loadkeys "$keymap" >>"$YAAP_LOG" 2>&1 || true
}

configure_clock() {
    local tz; tz="$(cfg_get locale.timezone)"; tz="${tz:-UTC}"
    arch-chroot "$TARGET_ROOT" timedatectl set-timezone "$tz" >>"$YAAP_LOG" 2>&1 || true
    arch-chroot "$TARGET_ROOT" hwclock --systohc >>"$YAAP_LOG" 2>&1 || die "hwclock failed"
}

configure_hostname() {
    local hn; hn="$(cfg_get system.hostname)"
    if [ -z "$hn" ]; then
        if [ "${YAAP_UNATTENDED:-0}" = 1 ]; then hn="yaaplinux"; else
            ui_input "yaaplinux" "Hostname"; hn="$REPLY"
        fi
    fi
    cfg_set system.hostname "$hn"
    echo "$hn" > "$TARGET_ROOT/etc/hostname"
    {
        echo "127.0.0.1   localhost"
        echo "::1         localhost"
        echo "127.0.1.1   $hn.localdomain $hn"
    } > "$TARGET_ROOT/etc/hosts"
    log_info "hostname: $hn"
}

install_microcode() {
    local mc; mc="$(cfg_get hardware.cpu.microcode)"
    case "$mc" in
        intel-ucode|amd-ucode) pkg_install "$mc" ;;
        *) log_warn "no microcode package resolved" ;;
    esac
    log_info "microcode: $mc"
}

configure_initramfs() {
    log_info "configuring mkinitcpio hooks (systemd + btrfs, sd-encrypt if LUKS, resume if hibernation)"
    local hooks="base systemd autodetect modconf block keymap consolefont keyboard btrfs"
    local has_hib; has_hib="$(cfg_get disk.swap.hibernation)"
    [ "$has_hib" = true ] && hooks="$hooks resume"
    # sd-encrypt provides the LUKS passphrase prompt via the systemd hook; add
    # it only when LUKS is enabled (a bare legacy `encrypt` hook is wrong next
    # to the `systemd` hook).
    [ "$(cfg_get disk.luks.enabled)" = true ] && hooks="$hooks sd-encrypt"

    cat > "$TARGET_ROOT/etc/mkinitcpio.conf" <<EOF
# Generated by YaapLinux installer
HOOKS=($hooks)
MODULES=()
COMPRESSION="zstd"
EOF

    if [ "$has_hib" = true ]; then
        mkdir -p "$TARGET_ROOT/etc/initramfs.conf.d"
        local ruuid off
        ruuid="$(luks_or_root_uuid)"
        off="$(cfg_get disk.swap.resume_offset)"
        { echo "RESUME=UUID=$ruuid"; [ -n "$off" ] && echo "RESUME_OFFSET=$off"; } \
            > "$TARGET_ROOT/etc/initramfs.conf.d/resume.conf"
    fi

    arch-chroot "$TARGET_ROOT" mkinitcpio -P >>"$YAAP_LOG" 2>&1 || die "mkinitcpio failed"
}

luks_or_root_uuid() {
    if [ "$(cfg_get disk.luks.enabled)" = true ]; then
        local part; part="$(cfg_get storage.root_partition)"
        # LUKS UUID is the container's; the resume device is the mapped one.
        blkid -s UUID -o value "/dev/mapper/$(cfg_get disk.luks.open_mapper)" 2>/dev/null \
            || cfg_get storage.root_uuid
    else
        cfg_get storage.root_uuid
    fi
}

create_user() {
    local name shell groups
    name="$(cfg_get user.name)"
    if [ -z "$name" ]; then
        if [ "${YAAP_UNATTENDED:-0}" = 1 ]; then
            log_warn "no user.name set; skipping interactive user creation"
            return 0
        fi
        ui_input "" "Username for daily use"
        name="$REPLY"
        cfg_set user.name "$name"
    fi
    shell="$(cfg_get user.shell)"; shell="${shell:-/bin/bash}"

    if ! arch-chroot "$TARGET_ROOT" id "$name" >/dev/null 2>&1; then
        arch-chroot "$TARGET_ROOT" useradd -m -s "$shell" "$name" >>"$YAAP_LOG" 2>&1 \
            || die "useradd failed for $name"
        # Set a password (unattended: random; else prompt).
        if [ "${YAAP_UNATTENDED:-0}" = 1 ]; then
            local pw; pw="$(head -c 18 /dev/urandom | base64 | head -c 16)"
            printf '%s\n%s\n' "$pw" "$pw" | arch-chroot "$TARGET_ROOT" passwd "$name" >>"$YAAP_LOG" 2>&1 || true
            log_info "unattended: generated a random password for $name"
        else
            arch-chroot "$TARGET_ROOT" passwd "$name" >>"$YAAP_LOG" 2>&1 || die "passwd failed for $name"
        fi
    fi

    # Supplementary groups from config + GPU-derived set.
    local grp="wheel"
    [ "$(cfg_get hardware.gpu.primary)" != "unknown" ] && grp="$grp video render audio input storage"
    [ "$(cfg_get peripherals.printer)" = yes ] && grp="$grp lp"
    [ "$(cfg_get peripherals.scanner)" = yes ] && grp="$grp scanner"
    local extra; extra="$(cfg_array user.groups_extra)"
    for g in $extra; do grp="$grp $g"; done
    arch-chroot "$TARGET_ROOT" usermod -aG "$grp" "$name" >>"$YAAP_LOG" 2>&1 \
        || log_warn "could not set supplementary groups"
    log_info "user $name groups: $grp"
}

configure_sudo() {
    mkdir -p "$TARGET_ROOT/etc/sudoers.d"
    cat > "$TARGET_ROOT/etc/sudoers.d/00-wheel-nopasswd_prompt" <<'EOF'
# YaapLinux: wheel members may use sudo (prompt for password).
%wheel ALL=(ALL:ALL) ALL
EOF
    chmod 0440 "$TARGET_ROOT/etc/sudoers.d/00-wheel-nopasswd_prompt"
    arch-chroot "$TARGET_ROOT" visudo -cf /etc/sudoers.d/00-wheel-nopasswd_prompt >>"$YAAP_LOG" 2>&1 \
        || log_warn "sudoers drop-in validation failed"
}

configure_network() {
    log_info "network: NetworkManager + iwd backend"
    pkg_install networkmanager iwd
    arch-chroot "$TARGET_ROOT" systemctl enable NetworkManager.service >>"$YAAP_LOG" 2>&1 \
        || die "could not enable NetworkManager"
    # iwd as the WiFi backend.
    cat > "$TARGET_ROOT/etc/NetworkManager/conf.d/10-iwd.conf" <<'EOF'
[general]
WifiBackend=iwd
EOF
    log_info "NetworkManager enabled with iwd backend"
}

# Copy the installer + config + assets into the target for resumption/audit.
copy_installer_artifacts() {
    local dst="$TARGET_ROOT/etc/yaaplinux"
    mkdir -p "$dst"
    cp "$(_cfg_path)" "$dst/install-config.yaml" 2>/dev/null || true
    if [ -d "$SCRIPT_DIR/lib" ]; then
        cp -a "$SCRIPT_DIR" "$TARGET_ROOT/opt/yaaplinux" 2>/dev/null || true
    fi
    # Install pacman hooks (snapper, gutenprint) if present.
    install_hooks
    log_info "installer artifacts copied to $dst and /opt/yaaplinux"
}

install_hooks() {
    local src="$ASSETS_DIR/hooks" dst="$TARGET_ROOT/etc/pacman.d/hooks"
    [ -d "$src" ] || return 0
    mkdir -p "$dst"
    cp "$src"/*.hook "$dst/" 2>/dev/null || true
    log_info "installed pacman hooks -> $dst"
}
